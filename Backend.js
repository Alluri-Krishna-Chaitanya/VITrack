// --- Helper: distance between two lat/lng ---
function getDistance(a,b){
  const R=6371000;
  const toRad=x=>x*Math.PI/180;
  const dLat=toRad(b[0]-a[0]);
  const dLng=toRad(b[1]-a[1]);
  const lat1=toRad(a[0]);
  const lat2=toRad(b[0]);
  const aVal=Math.sin(dLat/2)**2 +
             Math.cos(lat1)*Math.cos(lat2)*
             Math.sin(dLng/2)**2;
  return R*2*Math.atan2(Math.sqrt(aVal), Math.sqrt(1-aVal));
}

// --- Animate shuttle along route ---
let idx = 0;
let paused = false;
const marker = L.marker(mensHostelRoute[0], { title: 'Shuttle' })
  .addTo(map)
  .bindPopup('Shuttle');

function isCheckpoint(pos){
  return checkpoints.some(cp=>getDistance(pos, cp)<5);
}

function moveShuttle(){
  if(paused) return;
  idx = (idx + 1) % mensHostelRoute.length;
  const pos = mensHostelRoute[idx];
  marker.setLatLng(pos);
  if(isCheckpoint(pos)){
    paused = true;
    setTimeout(()=>{ paused=false; }, 2000);
  }
}
setInterval(moveShuttle, 500);
